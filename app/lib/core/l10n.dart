///
/// Les clés manquantes dans une langue retombent sur le français ; une clé
/// absente partout est affichée telle quelle (visible en recette).
class L10n {
  const L10n._(this.code);

  final String code;

  static const supported = [Locale('fr'), Locale('en'), Locale('ar')];

  static L10n of(Locale locale) => L10n._(_strings.containsKey(locale.languageCode) ? locale.languageCode : 'fr');

  static Locale resolve(Locale device) =>
      supported.firstWhere((l) => l.languageCode == device.languageCode, orElse: () => const Locale('fr'));

  static String languageName(String code) => switch (code) {
        'en' => 'English',
        'ar' => 'العربية',
        _ => 'Français',
      };

  String? tryT(String key, [Map<String, Object?> args = const {}]) {
    final raw = _strings[code]![key] ?? _strings['fr']![key];
    if (raw == null) return null;
    var out = raw;
    args.forEach((k, v) => out = out.replaceAll('{$k}', '${v ?? ''}'));
    return out;
  }

  String t(String key, [Map<String, Object?> args = const {}]) => tryT(key, args) ?? key;

  static Map<String, Map<String, String>> get strings => _strings;
}

extension L10nContext on BuildContext {
  String tr(String key, [Map<String, Object?> args = const {}]) => L10n.of(AppScope.of(this).locale).t(key, args);

  String? tryTr(String key, [Map<String, Object?> args = const {}]) => L10n.of(AppScope.of(this).locale).tryT(key, args);
}

